# 一对中有多个信息时，可以用列表嵌套字典的方式来放置
phones = [
    {"名称": "华为P60", "价格": 4887.00, "销量": 210},
    {"名称": "华为Mate40EPro", "价格": 4699.00, "销量": 90},
    {"名称": "华为nova10青春版", "价格": 1698.00, "销量": 102},
    {"名称": "华为P50Pro", "价格": 3987.00, "销量": 88},
    {"名称": "华为畅享70", "价格": 999.00, "销量": 152}
]

# list.sort(key=None, reverse=False) key为指定排序的依据
phones.sort(key = lambda x:x["销量"],reverse = True)

for i in phones:
    print(i)
